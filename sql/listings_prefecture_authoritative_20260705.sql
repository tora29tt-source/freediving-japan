-- ステータス: 実行済み（2026-07-05・Chrome MCP経由でSupabase本番に直接適用済み）
-- ============================================================
-- listings.prefecture を検索の正データにする対応
-- 2026-07-05
--
-- 背景（Takuyaとの会話で確定）：
-- コース登録フォームの「エリア」チップは14種の固定リストで、
-- リストに無い地名（例：鹿児島）は毎回手動でファイルを直さないと
-- 選べず、日本全国・海外をカバーするには無理がある構造だった。
--
-- 対応：
-- 47都道府県＋「海外」を正式なprefecture値として固定（CHECK制約）し、
-- 探すページの検索・絞り込みはこちらを正とする。
-- 従来のエリア（area）チップ14種は「人気スポット」タグとして残すが、
-- 任意入力に格下げ（都道府県だけでも検索対象になる）。
-- 海外掲載時の国名は新設の country カラムに格納する
-- （prefecture='海外'のときのみ使用。prefecture自体は「海外」で
-- 統一し、フィルタ側は国名を意識せず「海外」として絞り込める）。
--
-- 事前確認（2026-07-05）：既存データは NULL(4件) / 沖縄県(3件) / 静岡県(2件)
-- のみで、すべて下記CHECK制約の許可リストに含まれるため、追加は無害。
-- ============================================================

ALTER TABLE listings
  ADD COLUMN IF NOT EXISTS country TEXT;

ALTER TABLE listings
  DROP CONSTRAINT IF EXISTS listings_prefecture_check;

ALTER TABLE listings
  ADD CONSTRAINT listings_prefecture_check
  CHECK (prefecture IS NULL OR prefecture IN (
    '北海道',
    '青森県','岩手県','宮城県','秋田県','山形県','福島県',
    '茨城県','栃木県','群馬県','埼玉県','千葉県','東京都','神奈川県',
    '新潟県','富山県','石川県','福井県','山梨県','長野県','岐阜県','静岡県','愛知県',
    '三重県','滋賀県','京都府','大阪府','兵庫県','奈良県','和歌山県',
    '鳥取県','島根県','岡山県','広島県','山口県',
    '徳島県','香川県','愛媛県','高知県',
    '福岡県','佐賀県','長崎県','熊本県','大分県','宮崎県','鹿児島県','沖縄県',
    '海外'
  ));

CREATE INDEX IF NOT EXISTS idx_listings_prefecture ON listings(prefecture);
